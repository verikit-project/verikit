import type {
  FieldInfo,
  LoadedResource,
  RelationshipInfo,
} from "./load-resources.js";
import { pluralCamelCase, pluralSnakeCase, snakeCase } from "./names.js";

export type Dialect = "sqlite" | "postgresql";

export const GENERATED_HEADER = (source: string) =>
  `// Generated by \`verikit generate:schema\` from ${source}. Don't edit this\n// file: your changes would be overwritten. Change the source instead.\n`;

interface Column {
  /** Builder call, e.g. `text("title")`. */
  call: string;
  /** Builder functions imported from drizzle-orm. */
  imports: string[];
}

type ColumnMapper = (column: string, field: FieldInfo) => Column;

function optionKinds(field: FieldInfo): Set<string> {
  return new Set((field.options ?? []).map((option) => typeof option.value));
}

function isInteger(field: FieldInfo): boolean {
  if (field.fieldType === "select") {
    // Only reached for a select whose options are all numbers.
    return field.options!.every((option) => Number.isInteger(option.value));
  }

  return field.step !== undefined && Number.isInteger(field.step);
}

const SQLITE: Record<string, ColumnMapper> = {
  boolean: (c) => ({
    call: `integer("${c}", { mode: "boolean" })`,
    imports: ["integer"],
  }),
  number: (c, f) =>
    isInteger(f)
      ? { call: `integer("${c}")`, imports: ["integer"] }
      : { call: `real("${c}")`, imports: ["real"] },
  json: (c) => ({
    call: `text("${c}", { mode: "json" }).$type<string[]>()`,
    imports: ["text"],
  }),
  text: (c) => ({ call: `text("${c}")`, imports: ["text"] }),
  date: (c) => ({ call: `text("${c}")`, imports: ["text"] }),
  datetime: (c) => ({ call: `text("${c}")`, imports: ["text"] }),
};

const POSTGRES: Record<string, ColumnMapper> = {
  boolean: (c) => ({ call: `boolean("${c}")`, imports: ["boolean"] }),
  number: (c, f) =>
    isInteger(f)
      ? { call: `integer("${c}")`, imports: ["integer"] }
      : { call: `doublePrecision("${c}")`, imports: ["doublePrecision"] },
  json: (c) => ({
    call: `jsonb("${c}").$type<string[]>()`,
    imports: ["jsonb"],
  }),
  text: (c) => ({ call: `text("${c}")`, imports: ["text"] }),
  date: (c) => ({
    call: `date("${c}", { mode: "string" })`,
    imports: ["date"],
  }),
  datetime: (c) => ({
    call: `timestamp("${c}", { mode: "string", withTimezone: true })`,
    imports: ["timestamp"],
  }),
};

/** Which column kind stores a field's values. */
function columnKind(field: FieldInfo): string {
  switch (field.fieldType) {
    case "boolean":
    case "number":
    case "date":
    case "datetime":
      return field.fieldType;
    case "file":
    case "image":
      return field.multiple ? "json" : "text";
    case "select": {
      const kinds = optionKinds(field);
      if (kinds.size === 1 && kinds.has("number")) return "number";
      if (kinds.size === 1 && kinds.has("boolean")) return "boolean";
      return "text";
    }
    default:
      return "text";
  }
}

function isPrimitive(value: unknown): value is string | number | boolean {
  return ["string", "number", "boolean"].includes(typeof value);
}

/** Generated Drizzle schema plus warnings about resource/storage mismatches. */
export interface RenderedSchema {
  source: string;
  warnings: string[];
}

/** Source for `db/schema.ts`: one table per resource plus a `tables` map. */
export function renderSchema(
  resources: readonly LoadedResource[],
  dialect: Dialect,
  options: { customSchema?: string } = {},
): RenderedSchema {
  const mappers = dialect === "sqlite" ? SQLITE : POSTGRES;
  const tableFn = dialect === "sqlite" ? "sqliteTable" : "pgTable";
  const imports = new Set([tableFn, "text", "integer"]);
  const warnings: string[] = [];
  const tableNames = new Map(
    resources.map((resource) => [
      resource.name,
      pluralCamelCase(resource.name),
    ]),
  );
  const owners = new Map<string, string>([["tables", "the tables map"]]);

  for (const [resource, table] of tableNames) {
    const owner = owners.get(table);

    if (owner) {
      throw new Error(
        `Resource "${resource}" would generate the table export "${table}", which ${owner} already uses. Rename the resource.`,
      );
    }

    owners.set(table, `resource "${resource}"`);
  }

  const tables = resources.map((resource) => {
    if (resource.hasTable) {
      throw new Error(
        `Resource "${resource.name}" (${resource.file}) sets \`table\`. generate:schema creates tables from resources, so remove \`table\` and let the server pass the generated one.`,
      );
    }

    const references = foreignKeyReferences(resource, tableNames, warnings);
    const columns = Object.entries(resource.fields).map(([name, field]) => {
      const column = mappers[columnKind(field)](snakeCase(name), field);
      column.imports.forEach((fn) => imports.add(fn));
      return `  ${name}: ${column.call}${modifiers(resource, name, field, warnings)}${references.get(name) ?? ""},`;
    });

    return `export const ${tableNames.get(resource.name)} = ${tableFn}("${pluralSnakeCase(resource.name)}", {
  id: text("id")
    .primaryKey()
    .$defaultFn(() => crypto.randomUUID()),
${columns.join("\n")}
  // Lets the server reject stale writes to protected resources.
  revision: integer("revision").notNull().default(0),
});
`;
  });

  const map = resources
    .map((resource) => `  ${resource.name}: ${tableNames.get(resource.name)},`)
    .join("\n");
  const custom = options.customSchema
    ? `\nexport * from "./${options.customSchema}";\n`
    : "";

  return {
    source: `${GENERATED_HEADER("resources/")}// After it changes, run \`npm run db:generate\` to create a migration.
import { ${[...imports].sort().join(", ")} } from "drizzle-orm/${dialect === "sqlite" ? "sqlite" : "pg"}-core";
${custom}
${tables.join("\n")}
/** Each resource's table, by resource name. */
export const tables = {
${map}
};
`,
    warnings,
  };
}

function modifiers(
  resource: LoadedResource,
  name: string,
  field: FieldInfo,
  warnings: string[],
): string {
  const hasDefault = isPrimitive(field.defaultValue);
  const parts: string[] = [];

  if (!field.nullable && (field.required || hasDefault)) {
    parts.push(".notNull()");
  } else if (!field.nullable) {
    warnings.push(
      `${resource.name}.${name} is optional but not nullable: a row saved without it is read back as null, which the field rejects when editing. Add .nullable() or .required() to the field.`,
    );
  }

  if (hasDefault) {
    parts.push(`.default(${JSON.stringify(field.defaultValue)})`);
  }

  if (field.unique) {
    parts.push(".unique()");
  }

  return parts.join("");
}

function foreignKeyReferences(
  resource: LoadedResource,
  tableNames: ReadonlyMap<string, string>,
  warnings: string[],
): Map<string, string> {
  const references = new Map<string, string>();

  for (const [name, relationship] of Object.entries(resource.relationships)) {
    const reference = foreignKeyReference(relationship, tableNames);

    if (reference) {
      references.set(reference.field, reference.call);
    } else if (relationship.relationshipType === "belongsToMany") {
      warnings.push(
        `${resource.name}.${name} is belongsToMany: generate:schema doesn't create join tables. Define it in db/custom-schema.ts.`,
      );
    }
  }

  return references;
}

function foreignKeyReference(
  relationship: RelationshipInfo,
  tableNames: ReadonlyMap<string, string>,
): { field: string; call: string } | undefined {
  const target = tableNames.get(relationship.resource);

  if (
    relationship.relationshipType !== "belongsTo" ||
    typeof relationship.foreignKey !== "string" ||
    !target
  ) {
    return undefined;
  }

  return {
    field: relationship.foreignKey,
    call: `.references(() => ${target}.id)`,
  };
}
